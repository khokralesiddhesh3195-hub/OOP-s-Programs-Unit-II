#include <iostream>              // Includes the iostream library for input and output operations

using namespace std;             // Allows us to use standard C++ objects like cout and endl without std::

int main() {                      // Main function where the program execution begins

    int roll = 101;               // Declares an integer variable 'roll' and initializes it with 101

    char grade = 'A';             // Declares a character variable 'grade' and initializes it with 'A'

    float fee = 12500.50;         // Declares a floating-point variable 'fee' and initializes it with 12500.50

    cout << "Roll No: " << roll << endl;   // Displays the roll number on the screen

    cout << "Grade: " << grade << endl;    // Displays the grade on the screen

    cout << "Fee: " << fee << endl;        // Displays the fee on the screen

    return 0;                     // Returns 0 to indicate successful program execution
}
